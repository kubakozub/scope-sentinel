"""Best-effort conversion of a pasted, plain-text scope list into the
scope-sentinel format.

This is a *heuristic*. Program scope pages come in every shape — bullet lists,
markdown tables, headings, prose — so this module extracts host/URL/IP tokens
and buckets them under in-scope / out-of-scope sections. Always review the
output before trusting it.

Rules of thumb:
* Section headers are recognised case-insensitively: anything containing "out
  of scope", "not in scope", "excluded"/"exclusions" starts an out-of-scope
  section; "in scope" / "scope" / "targets" / "assets" starts an in-scope one.
* Any line that itself contains a host/URL/IP token is treated as data (so a
  domain like ``in-scope.example.com`` is not mistaken for a header).
* Tokens seen before any header default to in-scope.
* Common source-file names (``README.md``, ``config.py``, ...) are filtered out.
"""
from __future__ import annotations

import json
import re

_MDLINK = re.compile(r'\[[^\]]*\]\((?P<url>[^)]+)\)')
_HEADER_TRIM = re.compile(r'^[\s#>*+\-_.:|]+|[\s#*+\-_:|]+$')

_IPV4 = re.compile(r'\b\d{1,3}(?:\.\d{1,3}){3}(?:/\d{1,2})?\b')
_IPV6 = re.compile(r'\b(?:[A-Fa-f0-9]{1,4}:){2,7}[A-Fa-f0-9]{1,4}(?:/\d{1,3})?\b')
_HOSTISH = re.compile(
    r'(?:https?://)?'
    r'(?:\*\.)?'
    r'(?:[A-Za-z0-9_-]+\.)+[A-Za-z]{2,}'
    r'(?:[:/][^\s,;<>"\'`]*)?'
)

# Two-label tokens ending in one of these are almost certainly file names, not
# in-scope hosts. Wildcards, paths and 3+ label hosts bypass this filter.
_FILE_EXT = {
    'md', 'txt', 'js', 'ts', 'py', 'rb', 'go', 'php', 'sh', 'json', 'yaml',
    'yml', 'html', 'htm', 'css', 'png', 'jpg', 'jpeg', 'gif', 'svg', 'pdf',
    'csv', 'xml', 'toml', 'ini', 'lock', 'log', 'zip', 'tar', 'gz',
}


def _clean_header(line):
    return _HEADER_TRIM.sub('', line).strip().lower()


def _section_of(line):
    h = _clean_header(line)
    if not h:
        return None
    # Check out-of-scope first: "out of scope" also contains "scope".
    if ('out of scope' in h or 'out-of-scope' in h or 'not in scope' in h
            or h.startswith('exclud') or 'exclusion' in h):
        return 'out_of_scope'
    if ('in scope' in h or 'in-scope' in h
            or h in ('scope', 'targets', 'target', 'assets', 'domains',
                     'in scope assets')):
        return 'in_scope'
    return None


def _is_noise(token):
    core = token.lower()
    if '://' in core:
        core = core.split('://', 1)[1]
    core = core.split('/', 1)[0].split(':', 1)[0]
    if '*' in core:
        return False
    labels = core.split('.')
    return len(labels) == 2 and labels[-1] in _FILE_EXT


def _extract_tokens(line):
    text = _MDLINK.sub(lambda m: ' ' + m.group('url') + ' ', line).replace('`', ' ')
    raw_tokens = []
    raw_tokens += (m.group(0) for m in _IPV4.finditer(text))
    raw_tokens += (m.group(0) for m in _IPV6.finditer(text))
    for m in _HOSTISH.finditer(text):
        # Skip the domain part of an email address (e.g. "you@example.com").
        if m.start() > 0 and text[m.start() - 1] == '@':
            continue
        raw_tokens.append(m.group(0))

    cleaned, seen = [], set()
    for tok in raw_tokens:
        tok = tok.strip().strip('.,;:').strip('()[]{}<>"\'')
        if not tok or _is_noise(tok):
            continue
        if tok.lower() in seen:
            continue
        seen.add(tok.lower())
        cleaned.append(tok)
    return cleaned


def _dedup(items):
    out, seen = [], set()
    for it in items:
        if it.lower() not in seen:
            seen.add(it.lower())
            out.append(it)
    return out


def parse_text(text):
    """Parse pasted text into ``{'in_scope': [...], 'out_of_scope': [...]}``."""
    result = {'in_scope': [], 'out_of_scope': []}
    current = None
    for raw in text.splitlines():
        if not raw.strip():
            continue
        tokens = _extract_tokens(raw)
        if tokens:
            result[current or 'in_scope'].extend(tokens)
        else:
            section = _section_of(raw)
            if section:
                current = section
    for key in result:
        result[key] = _dedup(result[key])
    return result


def _yaml_quote(value):
    s = str(value)
    if '"' in s and "'" not in s:
        return "'%s'" % s
    return '"%s"' % s.replace('"', "'")


def to_yaml(scope, program=None):
    out = ["# Generated by scope-sentinel convert-scope "
           "(heuristic best-effort -- review before use)",
           "program: %s" % _yaml_quote(program or "")]
    for key in ('in_scope', 'out_of_scope'):
        entries = scope.get(key) or []
        out.append("%s:" % key)
        for entry in entries:
            out.append("  - %s" % _yaml_quote(entry))
    return "\n".join(out) + "\n"


def to_json(scope, program=None):
    payload = {
        "program": program or "",
        "in_scope": list(scope.get('in_scope') or []),
        "out_of_scope": list(scope.get('out_of_scope') or []),
    }
    return json.dumps(payload, indent=2) + "\n"
